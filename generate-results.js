// node scripts/generate-results.js  - runs every experiment and writes docs/RESULTS.md
const fs = require('fs'), path = require('path');
for (const f of ['structures', 'algorithms', 'engine', 'experiments']) require(path.join(__dirname, '..', 'src', f + '.js'));
const D = globalThis.DAA;
let md = '# Experiment results\n\nGenerated by `node scripts/generate-results.js`. Operation counts are deterministic (seeded generators); wall times vary by machine.\n\n';
for (const e of D.EXPERIMENTS) {
  const r = e.run();
  md += '## ' + e.title + '\n\n*Family:* ' + e.family + '  \n*Theory:* ' + e.theory + '\n\n';
  md += '| ' + r.head.join(' | ') + ' |\n|' + r.head.map(() => '---').join('|') + '|\n';
  md += r.rows.map((x) => '| ' + x.join(' | ') + ' |').join('\n') + '\n\n';
  md += '**Risk: ' + r.risk.level + '.** ' + r.risk.why + '\n\n' + r.finding + '\n\n';
}
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'RESULTS.md'), md);
console.log('wrote docs/RESULTS.md');
